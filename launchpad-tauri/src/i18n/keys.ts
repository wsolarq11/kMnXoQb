export type AppLanguage = "auto" | "zh-CN" | "en-US";

export function t(key: LanguageKey, lang: AppLanguage): string {
  return (lang === "zh-CN" ? ZH_CN : EN_US)[key];
}

/** Positional placeholder fill ({0}, {1}, ...), mirroring the Rust format(). */
export function format(key: LanguageKey, lang: AppLanguage, args: (string | number)[]): string {
  let out = t(key, lang);
  args.forEach((arg, i) => {
    out = out.replace(new RegExp(`\\{${i}\\}`, "g"), String(arg));
  });
  return out;
}
